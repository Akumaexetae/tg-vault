#!/usr/bin/env node
/**
 * Build the SQL that merges a second Vault database into this one.
 *
 * Background: Tyler's install and Gabriel's install were pointed at two
 * different Supabase projects that share a common ancestor (same seed, diverged
 * early August 2026). Both sides have rows the other lacks. This generates the
 * inserts needed to bring the other side's rows in.
 *
 * Because both databases descend from the same seed, rows that exist on both
 * sides still carry the SAME primary key — so "on conflict (id) do nothing"
 * dedupes the shared history for free. Creator ids match too, which means no
 * remapping: a creator_id from their export points at the same creator here.
 *
 * Usage:
 *   node scripts/build-merge-sql.js <their-backup.json> [out.sql]
 *
 * Output defaults to TGvault-Backups/merge-<date>.sql, which is gitignored —
 * the file contains plaintext credentials, like every Vault backup.
 *
 * Nothing is written to the database. Read the SQL, then run it yourself in the
 * Supabase SQL editor of the project you are keeping.
 */

const fs = require('fs');
const path = require('path');

const [, , inPath, outArg] = process.argv;
if (!inPath) {
  console.error('usage: node scripts/build-merge-sql.js <their-backup.json> [out.sql]');
  process.exit(1);
}

const backup = JSON.parse(fs.readFileSync(inPath, 'utf8'));
const data = backup.data ?? backup;
const creators = data.creators ?? [];
const entries = data.entries ?? [];
const notes = data.notes ?? [];
const earnings = data.earnings ?? [];

/** Postgres literal. null stays NULL; everything else is quoted text. */
const lit = (v) => {
  if (v === null || v === undefined || v === '') return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
};
/** jsonb literal for custom_fields / history / socials. */
const json = (v) => `'${JSON.stringify(v ?? []).replace(/'/g, "''")}'::jsonb`;
const bool = (v) => (v ? 'true' : 'false');
/** Timestamps: keep theirs so history reads correctly after the merge. */
const ts = (v) => (v ? lit(v) : 'now()');

const out = [];
out.push('-- Vault merge — generated by scripts/build-merge-sql.js');
out.push(`-- Source: ${path.basename(inPath)} (exported ${backup.exported_at ?? 'unknown'})`);
out.push(`-- Generated: ${new Date().toISOString()}`);
out.push('--');
out.push('-- Run this in the SQL editor of the project you are KEEPING.');
out.push('-- Every statement is "do nothing" on conflict, so running it twice is safe');
out.push('-- and rows you already have are never overwritten.');
out.push('');
out.push('begin;');
out.push('');

// --- creators ---------------------------------------------------------------
out.push(`-- Creators (${creators.length}) — matched on id, then on name.`);
for (const c of creators) {
  out.push(
    `insert into creators (id, name, color, kind, status, revenue_share, start_date, contract_status, drive_folder_url, avatar_path, created_at, updated_at, updated_by)\n` +
      `values (${lit(c.id)}, ${lit(c.name)}, ${lit(c.color)}, ${lit(c.kind ?? 'creator')}, ${lit(c.status ?? 'active')}, ` +
      `${c.revenue_share ?? 'NULL'}, ${lit(c.start_date)}, ${lit(c.contract_status ?? 'none')}, ${lit(c.drive_folder_url)}, ` +
      `${lit(c.avatar_path)}, ${ts(c.created_at)}, ${ts(c.updated_at)}, ${lit(c.updated_by ?? 'Gabriel')})\n` +
      `on conflict (id) do nothing;`,
  );
}
out.push('');
out.push('-- NOTE: creators are never deleted here. entries.creator_id is');
out.push('-- "on delete cascade", so removing a duplicate creator would silently take');
out.push('-- its accounts with it. If the same creator exists twice under different');
out.push('-- ids after the merge, repoint the entries first, then delete by hand:');
out.push('--   select id, name from creators order by name;');
out.push('');

// --- entries ----------------------------------------------------------------
out.push(`-- Entries (${entries.length}).`);
out.push('-- Guarded twice: by id (shared history) and by service+username');
out.push('-- (the same account re-added by hand on the other side).');
for (const e of entries) {
  out.push(
    `insert into entries (id, service_name, service_key, service_url, creator_id, username, password, totp_secret, recovery, custom_fields, notes, proxy, pinned, history, created_at, updated_at, updated_by)\n` +
      `select ${lit(e.id)}, ${lit(e.service_name)}, ${lit(e.service_key ?? 'custom')}, ${lit(e.service_url ?? '')}, ${lit(e.creator_id)}, ` +
      `${lit(e.username)}, ${lit(e.password ?? '')}, ${lit(e.totp_secret)}, ${lit(e.recovery)}, ${json(e.custom_fields)}, ` +
      `${lit(e.notes)}, ${lit(e.proxy)}, ${bool(e.pinned)}, ${json(e.history)}, ${ts(e.created_at)}, ${ts(e.updated_at)}, ${lit(e.updated_by ?? 'Gabriel')}\n` +
      `where not exists (\n` +
      `  select 1 from entries x where x.service_key = ${lit(e.service_key ?? 'custom')} and lower(x.username) = lower(${lit(e.username)})\n` +
      `)\n` +
      `on conflict (id) do nothing;`,
  );
}
out.push('');

// --- secure notes -----------------------------------------------------------
if (notes.length) {
  out.push(`-- Secure notes (${notes.length}).`);
  for (const n of notes) {
    const cols = Object.keys(n);
    out.push(
      `insert into secure_notes (${cols.join(', ')})\n` +
        `values (${cols.map((k) => (typeof n[k] === 'boolean' ? bool(n[k]) : typeof n[k] === 'object' && n[k] !== null ? json(n[k]) : lit(n[k]))).join(', ')})\n` +
        `on conflict (id) do nothing;`,
    );
  }
  out.push('');
}

// --- earnings ---------------------------------------------------------------
if (earnings.length) {
  out.push(`-- Creator earnings (${earnings.length}).`);
  for (const r of earnings) {
    const cols = Object.keys(r);
    out.push(
      `insert into creator_earnings (${cols.join(', ')})\n` +
        `values (${cols.map((k) => (typeof r[k] === 'number' ? r[k] : typeof r[k] === 'boolean' ? bool(r[k]) : typeof r[k] === 'object' && r[k] !== null ? json(r[k]) : lit(r[k]))).join(', ')})\n` +
        `on conflict (id) do nothing;`,
    );
  }
  out.push('');
}

out.push('commit;');
out.push('');
out.push('-- Check afterwards:');
out.push("--   select service_key, count(*) from entries group by 1 order by 2 desc;");
out.push('--   select count(*) from creators;');

const outPath =
  outArg ??
  path.join(
    __dirname,
    '..',
    'TGvault-Backups',
    `merge-${new Date().toISOString().slice(0, 10)}.sql`,
  );
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out.join('\n'), 'utf8');

console.log(`Read   : ${inPath}`);
console.log(`Source : ${creators.length} creators, ${entries.length} entries, ${notes.length} notes, ${earnings.length} earnings`);
console.log(`Wrote  : ${outPath}`);
console.log('\nReview it, then run it in the Supabase SQL editor of the project you are KEEPING.');
